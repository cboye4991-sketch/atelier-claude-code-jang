// Generates src/data/exercises.ts from the knowledge-base CSV.
// Only the PUBLIC_COLUMNS whitelist is read. Reference answers are never copied.
// Usage: npm run gen:exercises [-- path/to/file.csv]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PUBLIC_COLUMNS, parseCsv } from './csv.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = resolve(process.argv[2] ?? resolve(root, '../jang-source/jang_exercices_pc_ts2.csv'));
const outPath = resolve(root, 'src/data/exercises.ts');

const records = parseCsv(readFileSync(csvPath, 'utf8'));
if (records.length === 0) throw new Error(`No exercise found in ${csvPath}`);

const exercises = records.map((record) => {
  const pub = Object.fromEntries(PUBLIC_COLUMNS.map((name) => [name, (record[name] ?? '').trim()]));
  for (const name of ['ID', 'Chapitre', 'Enonce']) {
    if (!pub[name]) throw new Error(`Missing ${name} in a CSV row (ID: ${pub.ID || 'unknown'})`);
  }
  if (!/^JNG-PC-\d{2}$/.test(pub.ID)) throw new Error(`Unexpected exercise ID: ${pub.ID}`);
  return {
    id: pub.ID,
    chapter: pub.Chapitre,
    statement: pub.Enonce,
    data: pub.Donnees,
    validation: pub.Statut_validation,
  };
});

const ids = new Set(exercises.map((e) => e.id));
if (ids.size !== exercises.length) throw new Error('Duplicate exercise IDs in the CSV');

const body = `// GENERATED by scripts/generate-exercises.mjs from the knowledge-base CSV. Do not edit by hand.
// Public columns only (ID, Chapitre, Enonce, Donnees, Statut_validation). No reference answers.

export interface Exercise {
  /** Exercise ID, matches the knowledge base (JNG-PC-xx). */
  readonly id: string;
  /** Chapter label, prefixed by its subject ("Chimie — ..." or "Physique — ..."). */
  readonly chapter: string;
  readonly statement: string;
  /** Given constants and data, may be empty. */
  readonly data: string;
  /** Validation status of the reference answer, as written in the knowledge base. */
  readonly validation: string;
}

export const EXERCISES: readonly Exercise[] = ${JSON.stringify(exercises, null, 2)};
`;

writeFileSync(outPath, body, 'utf8');
console.log(`Wrote ${exercises.length} exercises to ${outPath}`);
